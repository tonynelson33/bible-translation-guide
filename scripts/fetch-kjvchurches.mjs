#!/usr/bin/env node
/**
 * Harvest kjvchurches.com's public GeoDirectory REST API (no auth required;
 * the site exposes /wp-json/geodir/v2/churches as standard WP REST discovery).
 * Every listing on the site is, by definition, KJV — that's the site's whole
 * premise, and the API's own `kjv_stance`/`bibles` fields confirm it per-row.
 *
 * Paced deliberately slowly (one request per ~3s) per explicit instruction —
 * this is a small, single-missionary-run site, not a corporate API. At
 * per_page=100 the full ~11,837-row directory is ~119 requests, so even at
 * this pace it's done in well under ten minutes and is far lighter than
 * crawling individual listing pages would have been.
 *
 * Output: scripts/kjvchurches.ndjson — one normalized record per line:
 *   {id, name, category, street, city, region, zip, lat, lon, phone,
 *    website, sourceUrl}
 * `category` is already mapped to our denomination slugs (see CATEGORY_MAP);
 * rows with no mappable category (e.g. "House Church" only) are dropped.
 */
import { appendFileSync, writeFileSync, existsSync } from "node:fs";

const UA = "bible-translation-guide/1.0 (church-directory enrichment; contact tonynelson33 via github)";
const BASE = "https://www.kjvchurches.com/wp-json/geodir/v2/churches";
const FIELDS = "id,title,link,post_category,street,city,region,zip,latitude,longitude,phone,website";
const PER_PAGE = 100;
const DELAY_MS = 3000;
const OUT = new URL("./kjvchurches.ndjson", import.meta.url);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Every Baptist-flavored top-level category here is self-tagged, not verified
// against any convention's own roster (spot-checked: a "Southern Baptist
// Church"-tagged listing turned out to be a Free Will Baptist church) — so
// all of them fold into the generic "Baptist (Independent/other)" bucket
// rather than the more specific sbc_church / missionary_baptist_church slugs,
// which are reserved for actual denomination-verified matches elsewhere.
const CATEGORY_MAP = [
  [/independent baptist church/i, "baptist_church"],
  [/missionary baptist church/i, "baptist_church"],
  [/southern baptist church/i, "baptist_church"],
  [/american baptist association/i, "baptist_church"],
  [/\bbible church\b/i, "bible_church"],
];

function mapCategory(postCategories) {
  const names = postCategories.map((c) => c.name);
  // Baptist-family tag wins if present alongside a Bible Church tag — most
  // double-tagged rows are Baptist churches that also picked up the more
  // generic label.
  for (const [re, slug] of CATEGORY_MAP) {
    if (slug !== "bible_church" && names.some((n) => re.test(n))) return "baptist_church";
  }
  if (names.some((n) => /\bbible church\b/i.test(n))) return "bible_church";
  return null;
}

const STATE_ABBREV = {
  Alabama: "AL", Alaska: "AK", Arizona: "AZ", Arkansas: "AR", California: "CA",
  Colorado: "CO", Connecticut: "CT", Delaware: "DE", "District of Columbia": "DC",
  Florida: "FL", Georgia: "GA", Hawaii: "HI", Idaho: "ID", Illinois: "IL",
  Indiana: "IN", Iowa: "IA", Kansas: "KS", Kentucky: "KY", Louisiana: "LA",
  Maine: "ME", Maryland: "MD", Massachusetts: "MA", Michigan: "MI",
  Minnesota: "MN", Mississippi: "MS", Missouri: "MO", Montana: "MT",
  Nebraska: "NE", Nevada: "NV", "New Hampshire": "NH", "New Jersey": "NJ",
  "New Mexico": "NM", "New York": "NY", "North Carolina": "NC",
  "North Dakota": "ND", Ohio: "OH", Oklahoma: "OK", Oregon: "OR",
  Pennsylvania: "PA", "Rhode Island": "RI", "South Carolina": "SC",
  "South Dakota": "SD", Tennessee: "TN", Texas: "TX", Utah: "UT",
  Vermont: "VT", Virginia: "VA", Washington: "WA", "West Virginia": "WV",
  Wisconsin: "WI", Wyoming: "WY",
};

// Titles are autogenerated as "{name} - {city}, {ST}" (or with an en-dash).
// Strip that suffix using the city/state we already have, rather than a
// generic regex, so compound-hyphenated city names (e.g. "Island
// City-Booneville") don't get mangled.
function cleanName(raw, city, region) {
  const abbrev = STATE_ABBREV[region];
  if (!abbrev) return raw;
  for (const dash of [" - ", " – "]) {
    const suffix = `${dash}${city}, ${abbrev}`;
    if (raw.endsWith(suffix)) return raw.slice(0, -suffix.length).trim();
  }
  return raw;
}

async function fetchPage(page) {
  const url = `${BASE}?per_page=${PER_PAGE}&page=${page}&_fields=${FIELDS}`;
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const r = await fetch(url, { headers: { "User-Agent": UA } });
      if (r.ok) return r.json();
      if ([429, 502, 503, 504].includes(r.status)) {
        await sleep(10000 * (attempt + 1));
        continue;
      }
      throw new Error(`HTTP ${r.status} on page ${page}`);
    } catch (e) {
      if (attempt === 4) throw e;
      await sleep(8000 * (attempt + 1));
    }
  }
}

(async () => {
  if (!existsSync(OUT)) writeFileSync(OUT, "");

  let page = 1;
  let kept = 0;
  let dropped = 0;
  for (;;) {
    const rows = await fetchPage(page);
    if (!rows || rows.length === 0) break;

    const lines = [];
    for (const r of rows) {
      const category = mapCategory(r.post_category || []);
      if (!category) {
        dropped++;
        continue;
      }
      const rec = {
        id: r.id,
        name: cleanName(r.title.raw, r.city, r.region),
        category,
        street: r.street || "",
        city: r.city || "",
        region: STATE_ABBREV[r.region] || r.region || "",
        zip: (r.zip || "").slice(0, 10),
        lat: r.latitude ? Number(r.latitude) : null,
        lon: r.longitude ? Number(r.longitude) : null,
        phone: r.phone || "",
        website: r.website || "",
        sourceUrl: r.link,
      };
      lines.push(JSON.stringify(rec));
      kept++;
    }
    if (lines.length) appendFileSync(OUT, lines.join("\n") + "\n");

    process.stdout.write(`\rpage ${page}  kept ${kept}  dropped(no mappable category) ${dropped}   `);
    page++;
    await sleep(DELAY_MS);
  }
  process.stdout.write("\n");
  console.log(`Done. ${kept} rows -> ${OUT.pathname}, ${dropped} dropped (no mappable category, e.g. House Church only).`);
})();
